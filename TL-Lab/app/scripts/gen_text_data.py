def fill(t: str) -> str:
    u, o = pick(UNIT), pick(OBJ)
    x = t.format(t=pick(TIME), u=u[0], ug=u[1], ui=u[2], o=o[0], ol=o[1], d=pick(DATE), n=pick(NUM),
                 k=R.randint(2, 4), rank=pick(RANK), name=pick(NAME))
    return x[0].upper() + x[1:]


def docs(per_class=26, demo=2) -> tuple[pd.DataFrame, pd.DataFrame]:
    old = pd.read_csv(ROOT / "data" / "docs" / "documents.csv")
    old["label"] = old["label"].replace({"org": "order"})
    rows, demo_rows = [], []
    for lab, tpls in TEMPLATES.items():
        have = old[old.label == lab].text.tolist()[:12]  # частина попередніх рукописних текстів лишається
        texts, seen = list(have), set(have)
        tries = 0
        while len(texts) < per_class + demo and tries < 2000:
            tries += 1
            x = fill(pick(tpls))
            if x not in seen:
                seen.add(x)
                texts.append(x)
        R.shuffle(texts)
        rows += [{"text": x, "label": lab} for x in texts[:per_class]]
        demo_rows += [{"text": x, "label": lab} for x in texts[per_class:per_class + demo]]
    return pd.DataFrame(rows), pd.DataFrame(demo_rows)


