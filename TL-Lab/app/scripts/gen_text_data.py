def messages(per_topic=10, demo_per_topic=1):
    old = pd.read_csv(ROOT / "data" / "messages" / "messages.csv")
    remap = {"забезпечення": "логістика"}
    old["ref_label"] = old["ref_label"].replace(remap)
    rows, demo_rows = [], []
    for topic, tpls in MSG.items():
        have = old[old.ref_label == topic].text.tolist()
        texts, seen, tries = list(have), set(have), 0
        while len(texts) < per_topic + demo_per_topic and tries < 2000:
            tries += 1
            x = fill(pick(tpls))
            if x not in seen:
                seen.add(x)
                texts.append(x)
        R.shuffle(texts)
        rows += [{"text": x, "ref_label": topic} for x in texts[:per_topic]]
        demo_rows += [{"text": x} for x in texts[per_topic:per_topic + demo_per_topic]]
    df = pd.DataFrame(rows).sample(frac=1, random_state=42).reset_index(drop=True)
    return df, pd.DataFrame(demo_rows)


